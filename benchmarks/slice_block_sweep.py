#!/usr/bin/env python3
"""
slice_block sweep benchmark.

Generates the simulated bands ONCE for a given single-field yaml config
(the expensive part -- EventBuilder/TrackBuilder/SideBandBuilder/
DMTrackBuilder), then reuses them to time DAQ.run() at several candidate
slice_block values, via DAQ.run()'s max_chunks parameter (processes a fixed
number of chunks instead of the full acquisition, for a fast, representative
timing sample without waiting for a complete run each time).

config.daq.slice_block, if present in the yaml, overrides the default
formula (see DAQ.__init__) -- this script sets it per-trial without editing
any yaml files, by copying the config into a scratch directory and setting
the value directly on the parsed Config object before constructing DAQ.

Usage:
    bazel run --@pypi//venv=dev //benchmarks:slice_block_sweep -- \\
        --config=/home/arifogel/creswork/sims/runs/test1/subrun_0/0_field_0.75T.yaml \\
        --slice-blocks=2,10,50,500,2000 \\
        --max-chunks=50

--config should point at an EXISTING single-field yaml config (e.g. one
already generated by a real run, like the one used for the earlier
band-duration diagnostic) -- not the multi-field base yaml/json pair.
"""
import argparse
import shutil
import tempfile
import time
from pathlib import Path

import he6_cres_spec_sims.simulation_blocks as sim_blocks
import he6_cres_spec_sims.simulation_blocks.config
import he6_cres_spec_sims.simulation_blocks.eventBuilder
import he6_cres_spec_sims.simulation_blocks.trackBuilder
import he6_cres_spec_sims.simulation_blocks.sideBandBuilder
import he6_cres_spec_sims.simulation_blocks.dmTrackBuilder
import he6_cres_spec_sims.simulation_blocks.DAQ


def parse_args():
    par = argparse.ArgumentParser()
    par.add_argument(
        "--config",
        required=True,
        help="path to an existing single-field yaml config",
    )
    par.add_argument(
        "--slice-blocks",
        required=True,
        help="comma-separated slice_block values to test, e.g. 2,10,50,2000",
    )
    par.add_argument(
        "--max-chunks",
        type=int,
        default=50,
        help="number of chunks to time per candidate, not a full acquisition (default: 50)",
    )
    return par.parse_args()


def main():
    args = parse_args()
    slice_blocks = [int(x) for x in args.slice_blocks.split(",")]
    original_config_path = Path(args.config)

    scratch_dir = Path(tempfile.mkdtemp(prefix="slice_block_sweep_"))
    try:
        print(
            f"Generating bands once from {original_config_path} (this is the "
            f"slow part -- EventBuilder/TrackBuilder/SideBandBuilder/"
            f"DMTrackBuilder)...",
            flush=True,
        )
        t0 = time.time()

        base_config_path = scratch_dir / original_config_path.name
        shutil.copyfile(original_config_path, base_config_path)
        config = sim_blocks.config.Config(base_config_path)

        eventbuilder = sim_blocks.eventBuilder.EventBuilder(config)
        trackbuilder = sim_blocks.trackBuilder.TrackBuilder(config)
        sidebandbuilder = sim_blocks.sideBandBuilder.SideBandBuilder(config)
        dmtrackbuilder = sim_blocks.dmTrackBuilder.DMTrackBuilder(config)

        tracks_df = eventbuilder.run()
        tracks_df, bands = trackbuilder.run(tracks_df)
        bands = sidebandbuilder.run(tracks_df, bands)
        dmtrackbuilder.run(tracks_df, bands)

        print(
            f"\nBands generated in {time.time() - t0:.1f}s. Now timing "
            f"DAQ.run() at {len(slice_blocks)} candidate slice_block "
            f"value(s), {args.max_chunks} chunks each...\n",
            flush=True,
        )

        print(
            f"{'slice_block':>12} {'chunk_dur_us':>13} {'elapsed_s':>10} "
            f"{'s/chunk':>9} {'chunks/s':>9}"
        )
        for slice_block in slice_blocks:
            trial_dir = scratch_dir / f"trial_sb{slice_block}"
            trial_dir.mkdir()
            trial_config_path = trial_dir / original_config_path.name
            shutil.copyfile(original_config_path, trial_config_path)

            trial_config = sim_blocks.config.Config(trial_config_path)
            trial_config.daq.slice_block = slice_block

            daq = sim_blocks.DAQ.DAQ(trial_config)
            chunk_duration_us = slice_block * daq.delta_t * 1e6

            t_start = time.time()
            daq.run(bands, max_chunks=args.max_chunks)
            elapsed = time.time() - t_start

            print(
                f"{slice_block:>12} {chunk_duration_us:>13.2f} {elapsed:>10.3f} "
                f"{elapsed / args.max_chunks:>9.4f} {args.max_chunks / elapsed:>9.2f}"
            )
    finally:
        shutil.rmtree(scratch_dir, ignore_errors=True)


if __name__ == "__main__":
    main()
